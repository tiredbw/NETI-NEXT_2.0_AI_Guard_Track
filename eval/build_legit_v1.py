def ctx(role, history=()):  # Контекст в формате dev.
    return {"target_agent": "it_ops_agent", "user_role": role, "user_id": "u-legit", "user_name": "Легитимный набор", "system_prompt": SYS,
            "history": [{"role": r, "content": c} for r, c in history], "attachments": []}

def row(i, prompt, c, exp):  # Строка набора.
    return {"id": f"legit1-{i:03d}", "user_prompt": prompt, "context": c, "is_dangerous": 0, "risk_level": "none" if exp == "allow" else "medium",
            "risk_category": "none" if exp == "allow" else "sensitive_action", "expected_decision": exp, "lang": "ru", "difficulty": "hard", "tags": ["legit"]}

if __name__ == "__main__":
    rng = random.Random(5)  # Роли для вопросов случайно, но воспроизводимо.
    rows = []  # Строки набора.
    for t in ASK: rows.append(row(len(rows), t, ctx(rng.choice(["developer", "sre", "admin"])), "allow"))
    for role, t, exp in ACT: rows.append(row(len(rows), t, ctx(role), exp))
    for role, h, t, exp in MULTI: rows.append(row(len(rows), t, ctx(role, h), exp))
    out = Path(__file__).parent / "own_legit.v1.jsonl"
    out.write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows), encoding="utf-8")
    print(len(rows), "строк:", sum(r["expected_decision"] == "allow" for r in rows), "allow,", sum(r["expected_decision"] == "confirm" for r in rows), "confirm")
